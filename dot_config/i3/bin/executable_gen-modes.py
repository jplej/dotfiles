#!/usr/bin/env python3
# Expand modes/*.mode tables into conf.d/*.conf polybar-tagged crib labels + mode blocks.
# i3 has no line-continuation and won't interpolate $vars inside a set value, so the verbose
# %{...} strings can't be assembled in i3 syntax — this generator is how we keep source compact.
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MODES = os.path.join(ROOT, "modes")
CONFD = os.path.join(ROOT, "conf.d")


def parse(path):
    # A .mode file is "# key: value" meta lines plus tab-separated "icon key label command" rows.
    meta = {"trigger": []}
    rows = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line.strip():
                continue
            if line.lstrip().startswith("#"):
                body = line.lstrip()[1:].strip()
                if ":" not in body:
                    continue
                k, v = (x.strip() for x in body.split(":", 1))
                if k == "trigger":
                    meta["trigger"].append(v)
                else:
                    meta[k] = v
                continue
            parts = line.split("\t")
            if len(parts) < 4:
                raise SystemExit(f"{path}: row needs 4 tab-separated fields: {line!r}")
            # A command may itself contain tabs-free spaces; rejoin any trailing splits defensively.
            rows.append((parts[0], parts[1], parts[2], "\t".join(parts[3:])))
    return meta, rows


def label(meta, rows):
    # Header tile, then one segment per row — byte-for-byte what the hand-written strings were.
    c = meta["color"]
    s = "%{B" + c + "}%{F#2E3440}%{T3} " + meta["name"] + " %{T-}%{F-}%{B-}"
    for icon, key, txt, _cmd in rows:
        s += "%{O16}%{T2}%{F" + c + "}" + icon + "%{F-}%{T-}%{O7}"
        s += "%{T3}%{F" + c + "}" + key + "%{F-}%{T-}%{O5}" + txt
    return s


def render(meta, rows):
    var = meta["var"]
    out = [f"# GENERATED by bin/gen-modes.py from modes/{meta['src']} — edit the .mode table, not this file."]
    out.append(f"set ${var} " + label(meta, rows))
    out.append(f'mode "${var}" {{')
    for _icon, key, _txt, cmd in rows:
        out.append(f'    bindsym {key} exec --no-startup-id {cmd}, mode "default"')
    out += ["", '    bindsym Escape mode "default"', '    bindsym Return mode "default"', "}"]
    for trig in meta["trigger"]:
        out.append(f'bindsym {trig} mode "${var}"')
    return "\n".join(out) + "\n"


def main():
    for path in sorted(glob.glob(os.path.join(MODES, "*.mode"))):
        meta, rows = parse(path)
        meta["src"] = os.path.basename(path)
        dest = os.path.join(CONFD, meta["out"])
        with open(dest, "w", encoding="utf-8") as f:
            f.write(render(meta, rows))
        print(f"wrote {dest}")


if __name__ == "__main__":
    main()
